"""Regenerate the fixed Level 1 field allowlist from V001 (no runtime SQL parsing)."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
ddl = (root / 'src/main/resources/db/migration/V001__create_common_tables.sql').read_text(encoding='utf-8')
names = ['languages', 'messages', 'message-translations', 'companies', 'sites', 'departments',
         'users', 'roles', 'user-roles', 'menus', 'buttons', 'menu-buttons', 'role-menu-permissions',
         'user-menu-permissions', 'role-button-permissions', 'user-button-permissions',
         'code-groups', 'codes']
private = {'PASSWORD_HASH', 'FAILED_LOGIN_COUNT', 'LOCKED_UNTIL', 'PASSWORD_CHANGED_AT',
           'MUST_CHANGE_PASSWORD_YN', 'LAST_LOGIN_AT', 'AUTH_TYPE'}
audit = {'USE_YN', 'CREATED_AT', 'CREATED_BY', 'UPDATED_AT', 'UPDATED_BY'}
definitions = []
for name, (table, body) in zip(names, re.findall(r'CREATE TABLE (TB_\w+) \((.*?)\n\);', ddl, re.S), strict=True):
    keys = re.search(r'PRIMARY KEY \((.*?)\)', body).group(1).replace(' ', '').split(',')
    fields = []
    identity = None
    for line in body.splitlines():
        match = re.match(r'\s+(\w+)\s+(VARCHAR2|CHAR|NUMBER|TIMESTAMP|DATE)(?:\((\d+)\))?(.*)', line)
        if not match:
            continue
        column, kind, length, extra = match.groups()
        if 'AS IDENTITY' in extra:
            identity = column
        if column in private or column in audit or column == identity:
            continue
        required = 'NOT NULL' in extra
        default = re.search(r"DEFAULT\s+('(?:[^']*)'|\d+|SYSDATE)", extra)
        default = default.group(1).strip("'") if default else None
        if default == 'SYSDATE':
            default = '@now'
        java_kind = {'VARCHAR2': 'TEXT', 'CHAR': 'TEXT', 'NUMBER': 'NUMBER', 'TIMESTAMP': 'TIME', 'DATE': 'TIME'}[kind]
        default_literal = 'null' if default is None else '"' + default + '"'
        fields.append(f'new Column("{column}", Kind.{java_kind}, {length or 0}, {str(required).lower()}, {default_literal})')
    quoted_keys = ', '.join('"' + key + '"' for key in keys)
    identity_literal = 'null' if identity is None else '"' + identity + '"'
    definitions.append(f'        new MasterResource("{name}", "{table}", List.of({quoted_keys}), {identity_literal}, List.of(\n            ' + ',\n            '.join(fields) + '))')
source = '''package com.erpcom.erpcom.common.master;

import java.util.List;

// Generated by scripts/generate_master_catalog.py. Identifiers never come from request data.
public final class MasterCatalog {
    private MasterCatalog() {}
    public enum Kind { TEXT, NUMBER, TIME }
    public record Column(String name, Kind kind, int length, boolean required, String defaultValue) {}
    public static final List<MasterResource> RESOURCES = List.of(
''' + ',\n'.join(definitions) + '''
    );
}
'''
target = root / 'src/main/java/com/erpcom/erpcom/common/master/MasterCatalog.java'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(source, encoding='utf-8', newline='\n')
print(f'Generated {len(definitions)} resource definitions.')
